/** Measure the existing portfolio artwork without changing image assets. */
import fs from "node:fs/promises";
import path from "node:path";
import { createRequire } from "node:module";
import ts from "typescript";

const require = createRequire(import.meta.url);
const nextRequire = createRequire(require.resolve("next/package.json"));
const sharp = nextRequire("sharp");
const root = process.cwd();
const ALPHA_THRESHOLD = 16;
const SAMPLE_LIMIT = 1600;

// Small optical corrections supplement geometry; they never override size caps.
const opticalBoosts = {
  Pocket: 1.04,
  Ultrasonium: 1.06,
  "Sunflower Labs": 1.04,
  "Aurelius Systems": 0.96,
  Valstad: 0.96,
  Atoms: 0.96,
  "Figure AI": 1.03,
  Apptronik: 1.1,
  "Reflect Orbital": 1.05,
  Exowatt: 1.06,
  "Apollo Atomics": 1.06,
  "MAV Unlimited": 1.12,
  Lance: 0.97,
  Hark: 0.96,
  "Maven Robotics": 0.94,
  "Plena Health": 1.06,
  "Core Automation": 1.08,
};
const bakedBackgrounds = {
  Atomarine: "dark-tile",
  Datoric: "light-checkerboard",
  Autostep: "dark-tile",
  Compresr: "dark-tile",
};
const stacked = new Set(["Core Automation", "Blue Origin", "Commons Clinic", "MAV Unlimited", "Array Labs"]);
const round = (value) => Math.round(value * 1_000_000) / 1_000_000;

const source = await fs.readFile(path.join(root, "src/lib/portfolio.ts"), "utf8");
const { outputText } = ts.transpileModule(source, {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
});
const portfolioModule = { exports: {} };
// Evaluate only the repository's local, trusted data module to preserve its order.
new Function("exports", outputText)(portfolioModule.exports);
const metrics = {};
for (const company of portfolioModule.exports.PORTFOLIO) {
  const src = (company.cardLogo ?? company.logo)?.split(/[?#]/, 1)[0];
  if (!src?.startsWith("/logos/")) throw new Error(`Missing local logo: ${company.name}`);
  const image = path.join(root, "public", src);
  const metadata = await sharp(image).metadata();
  const { data, info } = await sharp(image)
    .resize({ width: SAMPLE_LIMIT, height: SAMPLE_LIMIT, fit: "inside", withoutEnlargement: true })
    .ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  let left = info.width;
  let top = info.height;
  let right = -1;
  let bottom = -1;
  let weight = 0;
  let luma = 0;
  for (let y = 0; y < info.height; y++) {
    for (let x = 0; x < info.width; x++) {
      const index = (y * info.width + x) * 4;
      const alpha = data[index + 3];
      if (alpha < ALPHA_THRESHOLD) continue;
      left = Math.min(left, x);
      top = Math.min(top, y);
      right = Math.max(right, x);
      bottom = Math.max(bottom, y);
      const opacity = alpha / 255;
      weight += opacity;
      luma += (data[index] * 0.2126 + data[index + 1] * 0.7152 + data[index + 2] * 0.0722) / 255 * opacity;
    }
  }
  if (right < left || bottom < top || !metadata.width || !metadata.height) {
    throw new Error(`Empty or unmeasurable logo: ${company.name}`);
  }
  const width = right - left + 1;
  const height = bottom - top + 1;
  const meanLuminance = luma / weight;
  const kind = company.logoLabel && company.name !== "Core Automation" ? "icon" : "wordmark";
  metrics[src] = {
    name: company.name,
    intrinsicWidth: metadata.width,
    intrinsicHeight: metadata.height,
    inkBounds: {
      x: Math.round(left * metadata.width / info.width),
      y: Math.round(top * metadata.height / info.height),
      width: Math.round(width * metadata.width / info.width),
      height: Math.round(height * metadata.height / info.height),
    },
    crop: {
      left: round(left / info.width),
      top: round(top / info.height),
      width: round(width / info.width),
      height: round(height / info.height),
    },
    inkAspect: round(width / height),
    kind,
    ...(kind === "icon" ? { label: company.logoLabel } : {}),
    tone: meanLuminance > 0.7 ? "light" : meanLuminance < 0.35 ? "dark" : "mixed",
    meanLuminance: round(meanLuminance),
    inkCoverage: round(weight / (width * height)),
    visibleCoverage: round(weight / (info.width * info.height)),
    opticalBoost: opticalBoosts[company.name] ?? 1,
    ...(stacked.has(company.name) ? { stacked: true } : {}),
    ...(bakedBackgrounds[company.name] ? { bakedBackground: bakedBackgrounds[company.name] } : {}),
  };
}

const header = `// Generated by scripts/measure-company-logos.mjs from the 60 portfolio sources.\n// Bounds use alpha >= ${ALPHA_THRESHOLD}/255 at up to ${SAMPLE_LIMIT}px; original assets are untouched.\n\nexport type CompanyLogoMetric = {\n  name: string;\n  intrinsicWidth: number;\n  intrinsicHeight: number;\n  /** Visible source bounds in intrinsic pixels; opaque tiles include their background. */\n  inkBounds: { x: number; y: number; width: number; height: number };\n  /** Source-space crop fractions, each between zero and one. */\n  crop: { left: number; top: number; width: number; height: number };\n  inkAspect: number;\n  kind: "icon" | "wordmark";\n  label?: string;\n  tone: "dark" | "light" | "mixed";\n  meanLuminance: number;\n  /** Alpha-weighted coverage inside the visible bounds, for optical area sizing. */\n  inkCoverage: number;\n  visibleCoverage: number;\n  opticalBoost: number;\n  stacked?: boolean;\n  /** These sources cannot be recolored using their alpha mask alone. */\n  bakedBackground?: "dark-tile" | "light-checkerboard";\n};\n\nexport const COMPANY_LOGO_METRICS: Readonly<Record<string, CompanyLogoMetric>> = `;
const footer = `;\n\nexport function getCompanyLogoMetrics(source: string): CompanyLogoMetric | undefined {\n  const pathname = source.split(/[?#]/, 1)[0];\n  return Object.prototype.hasOwnProperty.call(COMPANY_LOGO_METRICS, pathname)\n    ? COMPANY_LOGO_METRICS[pathname]\n    : undefined;\n}\n`;
await fs.writeFile(path.join(root, "src/lib/company-logo-metrics.ts"), header + JSON.stringify(metrics, null, 2) + footer);
console.log(`Measured ${Object.keys(metrics).length} portfolio logo sources.`);
